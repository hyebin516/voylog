class BusinessHoursDay(BaseModel):
    open: Optional[str] = None
    close: Optional[str] = None


# Keyed by lowercase 3-letter weekday (mon..sun). A missing or null day means
# "not mentioned / unknown" -- never inferred, never treated as "closed".
BusinessHours = Dict[str, Optional[BusinessHoursDay]]


class PlaceTag(BaseModel):
    code: str
    confidence: float


class PlaceCandidate(BaseModel):
    name: str
    timestampSec: Optional[int] = None
    source: Literal["transcript", "on_screen_text", "hashtags", "description", "title"]
    confidence: float
    category: Optional[str] = None
    businessHours: Optional[BusinessHours] = None
    tags: List[PlaceTag] = []
    mentionNote: Optional[str] = None
    # Other spellings of this same place written in the title, description,
    # hashtags or on-screen text ("소베" when the transcript heard "소배").
    alternativeNames: List[str] = []

    # Tags are sometimes returned as bare codes (["베이커리 카페"]) instead of
    # {code, confidence} objects. Rejecting that threw away the whole
    # extraction -- a background enrichment failed outright over it -- so a
    # bare code is kept with a middling confidence instead.
    BARE_TAG_CONFIDENCE: ClassVar[float] = 0.6

    @field_validator("tags", mode="before")
    @classmethod
    def _accept_bare_tag_codes(cls, tags):
        if not isinstance(tags, list):
            return tags
        return [
            {"code": tag, "confidence": cls.BARE_TAG_CONFIDENCE} if isinstance(tag, str) else tag for tag in tags
        ]


