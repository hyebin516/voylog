class RoutePoint(BaseModel):
    order: int
    type: Literal["hotel", "place"]
    hotelId: Optional[str] = None
    placeId: Optional[str] = None
    name: str
    latitude: Optional[float] = None
    longitude: Optional[float] = None
    # What kind of place this is (cafe/restaurant/attraction/...), when the
    # request carried one. The backend stores it with any Kakao place it has
    # to create for a kept course, so the place can be found again by
    # category in 내 주변 추천.
    category: Optional[str] = None
    # Distance/duration of the leg arriving at this point from the previous
    # point in the optimized route -- null for the first point (order 0),
    # which has no preceding leg. Lets the UI show real per-stop "도보 N분"
    # rows instead of dividing the aggregate total evenly.
    legDistanceM: Optional[int] = None
    legDurationSec: Optional[int] = None
    # How that leg is travelled when a route mixes modes ("walk" or
    # "transit"); null when the whole route uses the route-level
    # transportMode. ("car" was used briefly for bookmark-folder routes
    # before they switched to buses and may remain in saved courses.)
    legTransportMode: Optional[Literal["walk", "transit", "car"]] = None
    # For a transit leg: which bus to take and between which stops, e.g.
    # "600번 · 온양온천역 신한은행 → 신정호관광지 건너".
    legGuidance: Optional[str] = None
    # The road the leg actually follows, as [[lat, lng], ...] -- Kakao returns
    # it on the same call that gives the distance and duration. Null when the
    # leg fell back to a straight-line estimate (Kakao unavailable), and on
    # routes saved before this was captured; the map draws a straight line
    # between the two stops in that case.
    legPath: Optional[List[List[float]]] = None


