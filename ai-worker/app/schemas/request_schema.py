from typing import Dict, List, Literal, Optional

from pydantic import BaseModel, Field

from app.schemas.response_schema import BusinessHours


class TranscriptRequest(BaseModel):
    youtubeUrl: str


class HashtagSearchRequest(BaseModel):
    hashtag: str
    maxResults: int = 20


class VideoSearchRequest(BaseModel):
    query: str
    maxResults: int = 20


class VideoMeta(BaseModel):
    videoId: str
    youtubeUrl: str
    title: Optional[str] = None
    description: Optional[str] = None
    hashtags: List[str] = []


class TranscriptSegment(BaseModel):
    text: str
    timestampSec: int


class PlaceExtractionRequest(BaseModel):
    video: VideoMeta
    transcript: List[TranscriptSegment]
    llmProvider: Literal["auto", "openai", "claude"] = "auto"
    # Runs the on-screen-text (OCR) pass even when a transcript exists.
    # That pass downloads the video and takes minutes, so it's off by
    # default and only used by the caller's background enrichment job --
    # never on the request a user is waiting on.
    forceScreenText: bool = False
    # The transcript is YouTube speech recognition, whose shop names are
    # often misheard -- the extraction prompt is told so, and the written
    # spellings from other sources are tried when a heard name can't be
    # found on the map.
    transcriptAutoGenerated: bool = False


class HotelInput(BaseModel):
    hotelId: str
    name: str
    latitude: float
    longitude: float
    address: Optional[str] = None


class CoursePointInput(BaseModel):
    """A start/end anchor for an FR-17 walking course. Unlike HotelInput
    this is not a saved `hotels` row -- it's a point the user picked on the
    map for this one course, so it has no owner and is never persisted on
    its own."""

    pointId: str
    name: str
    latitude: float
    longitude: float


class PlaceInput(BaseModel):
    placeId: str
    name: str
    latitude: float
    longitude: float


class RouteOptimizationRequest(BaseModel):
    startHotel: HotelInput
    endHotel: HotelInput
    places: List[PlaceInput]
    routeType: Literal["roundTrip", "hotelToHotel"] = "roundTrip"
    optimizationPriority: Literal["duration"] = "duration"
    transportMode: Literal["car", "walk", "transit"] = "car"


class PlaceRouteRequest(BaseModel):
    """Places to visit in the quickest order, with no hotel at either end."""

    places: List[PlaceInput]


class NearbyPlaceTagInput(BaseModel):
    code: str
    confidence: float


class NearbyPlaceCandidate(BaseModel):
    placeId: str
    name: str
    latitude: float
    longitude: float
    address: Optional[str] = None
    category: Optional[str] = None
    businessHours: Optional[BusinessHours] = None
    businessHoursIsEstimated: bool = False
    embedding: Optional[List[float]] = None
    tags: List[NearbyPlaceTagInput] = []


class NearbyScoreRequest(BaseModel):
    latitude: float
    longitude: float
    localTime: str
    radiusMeters: int = 2000
    limit: int = 20
    candidates: List[NearbyPlaceCandidate] = []
    userEmbedding: Optional[List[float]] = None
    userTagScores: Dict[str, float] = {}
    # One result per real spot (see app/utils/place_similarity.py), so the
    # nearby list doesn't show "케이락" and "케이락볼링장" as two cards.
    collapseSameSpots: bool = True


class GeocodeRequest(BaseModel):
    query: str


class PlaceSearchRequest(BaseModel):
    query: str
    size: int = 8


class ReverseGeocodeRequest(BaseModel):
    latitude: float
    longitude: float


class WalkingCourseRequest(BaseModel):
    regionName: str
    centerLatitude: float
    centerLongitude: float
    localTime: str
    radiusMeters: int = 3000
    bookmarkCandidates: List[NearbyPlaceCandidate] = []
    # Every other stored place near the center -- vlog places and public
    # dataset places (한국관광공사 / 소상공인 상가정보). Bookmarks alone were
    # too few per area, so courses kept cycling the same stops.
    placeCandidates: List[NearbyPlaceCandidate] = []
    userEmbedding: Optional[List[float]] = None
    userTagScores: Dict[str, float] = {}
    # FR-17 mood/duration filters (design handoff chips). Both optional --
    # None means "no preference", matching today's unfiltered behavior.
    mood: Optional[str] = None
    walkDuration: Optional[str] = None
    # Where the user chose to start and end the walk. Deliberately NOT a
    # hotel: a walking course start is an ephemeral point the user picked
    # on the map, unrelated to the trip planner's saved accommodations.
    # None keeps the cold-start behavior of anchoring the round trip on the
    # region's center point instead (no login required).
    startPoint: Optional[CoursePointInput] = None
    # Place ids from the course being regenerated, pushed down the ranking so
    # "다시 생성" comes back with different stops.
    avoidPlaceIds: List[str] = []


class SimilarTastePlaceCandidate(BaseModel):
    placeId: str
    name: str
    latitude: float
    longitude: float
    address: Optional[str] = None
    category: Optional[str] = None


class SimilarTasteUserInput(BaseModel):
    userId: str
    embedding: Optional[List[float]] = None
    bookmarkedPlaces: List[SimilarTastePlaceCandidate] = []


class SimilarTasteRequest(BaseModel):
    userEmbedding: List[float]
    otherUsers: List[SimilarTasteUserInput] = []
    limit: int = 20


class PlaceSummaryRequest(BaseModel):
    placeName: str
    notes: List[str] = []
    llmProvider: Literal["auto", "openai", "claude"] = "auto"


class EmbeddingRequest(BaseModel):
    text: str


# Upper bound per batch request; OpenAI accepts far more, but a nearby
# candidate list never needs more than this and it caps a runaway caller.
MAX_EMBEDDING_BATCH_SIZE = 200


class EmbeddingBatchRequest(BaseModel):
    texts: List[str] = Field(..., min_length=1, max_length=MAX_EMBEDDING_BATCH_SIZE)


class PreferenceUpdateRequest(BaseModel):
    currentEmbedding: Optional[List[float]] = None
    placeEmbedding: List[float]
    weight: float


class EmbeddingSimilarityTarget(BaseModel):
    key: str
    embedding: List[float]


class EmbeddingSimilarityRequest(BaseModel):
    embeddingA: List[float]
    embeddingsB: List[EmbeddingSimilarityTarget]
